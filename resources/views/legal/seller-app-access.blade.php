    <h1>17G Seller App Access</h1>
    <p><strong>Last updated:</strong> May 24, 2026</p>
    <p>17G Seller is a business companion app for verified 17G staff and merchant sellers. It is used to manage physical product sales, inventory, orders, delivery coordination, customer service records, and business reports.</p>

    <h2>Who Can Use the App</h2>
    <p>Accounts are issued by MMO 17G support after business verification. Access is role based so each authorized user only sees the seller, delivery, reporting, or profile tools assigned to their business role.</p>

    <h2>Business Model</h2>
    <p>The app supports sales operations for physical goods and services fulfilled outside the app. It does not sell or unlock digital content, subscriptions, premium app features, virtual currency, loans, fundraising, advertising impressions, app ratings, app reviews, rankings, or store-related actions.</p>

    <h2>Payments</h2>
    <p>Payment fields in the app are used by sellers to record payment status for physical orders, including cash on delivery, bank transfer, card, or KHQR records. These payments are for physical retail transactions and do not unlock digital content or app functionality.</p>

